CREATE TABLE IF NOT EXISTS public.wedding_fees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  year INTEGER NOT NULL,
  paid BOOLEAN NOT NULL DEFAULT FALSE,
  paid_date TIMESTAMPTZ,
  recorded_by UUID REFERENCES auth.users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (member_id, year)
);

ALTER TABLE public.wedding_fees ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "wedding_fees_select_access" ON public.wedding_fees;
CREATE POLICY "wedding_fees_select_access"
  ON public.wedding_fees
  FOR SELECT
  USING (
    EXISTS (
      SELECT 1
      FROM public.members m
      JOIN public.profiles p ON p.zone_id = m.zone_id
      WHERE m.id = public.wedding_fees.member_id
        AND p.id = auth.uid()
    )
    OR public.is_admin()
  );

DROP POLICY IF EXISTS "wedding_fees_insert_admin" ON public.wedding_fees;
CREATE POLICY "wedding_fees_insert_admin"
  ON public.wedding_fees
  FOR INSERT
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "wedding_fees_update_access" ON public.wedding_fees;
CREATE POLICY "wedding_fees_update_access"
  ON public.wedding_fees
  FOR UPDATE
  USING (
    EXISTS (
      SELECT 1
      FROM public.members m
      JOIN public.profiles p ON p.zone_id = m.zone_id
      WHERE m.id = public.wedding_fees.member_id
        AND p.id = auth.uid()
    )
    OR public.is_admin()
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.members m
      JOIN public.profiles p ON p.zone_id = m.zone_id
      WHERE m.id = public.wedding_fees.member_id
        AND p.id = auth.uid()
    )
    OR public.is_admin()
  );

DROP POLICY IF EXISTS "wedding_fees_delete_admin" ON public.wedding_fees;
CREATE POLICY "wedding_fees_delete_admin"
  ON public.wedding_fees
  FOR DELETE
  USING (public.is_admin());