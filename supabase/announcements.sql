CREATE TABLE IF NOT EXISTS public.announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL CHECK (length(trim(title)) > 0),
  category TEXT NOT NULL CHECK (
    category IN (
      'General',
      'Monthly Dues',
      'Additional Fees',
      'Chapel Meeting',
      'Chapel Activity',
      'Emergency'
    )
  ),
  description TEXT NOT NULL CHECK (length(trim(description)) > 0),
  target_audience TEXT NOT NULL CHECK (
    target_audience IN ('all_zone_treasurers', 'specific_zone')
  ),
  zone_id BIGINT REFERENCES public.zones(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
  created_by UUID DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  published_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  CONSTRAINT announcements_audience_zone_check CHECK (
    (target_audience = 'all_zone_treasurers' AND zone_id IS NULL)
    OR (target_audience = 'specific_zone' AND zone_id IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_announcements_published
  ON public.announcements(status, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_announcements_zone
  ON public.announcements(zone_id, status, published_at DESC);

CREATE OR REPLACE FUNCTION public.set_announcement_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at = NOW();
  IF TG_OP = 'UPDATE' THEN
    IF NEW.status = 'published'
      AND (OLD.status IS DISTINCT FROM NEW.status OR NEW.published_at IS NULL) THEN
      NEW.published_at = NOW();
    END IF;
  ELSIF NEW.status = 'published' AND NEW.published_at IS NULL THEN
    NEW.published_at = NOW();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS announcements_set_updated_at ON public.announcements;
CREATE TRIGGER announcements_set_updated_at
  BEFORE UPDATE ON public.announcements
  FOR EACH ROW
  EXECUTE FUNCTION public.set_announcement_updated_at();

UPDATE public.announcements
SET published_at = COALESCE(updated_at, created_at, NOW())
WHERE status = 'published'
  AND published_at IS NULL;

ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.announcements FROM anon;
REVOKE ALL ON public.announcements FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.announcements TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.announcements_id_seq TO authenticated;
REVOKE ALL ON SEQUENCE public.announcements_id_seq FROM anon;
REVOKE ALL ON SEQUENCE public.announcements_id_seq FROM PUBLIC;

DROP POLICY IF EXISTS "announcements_admin_manage" ON public.announcements;
CREATE POLICY "announcements_admin_manage"
  ON public.announcements
  FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "announcements_treasurer_read" ON public.announcements;
CREATE POLICY "announcements_treasurer_read"
  ON public.announcements
  FOR SELECT
  TO authenticated
  USING (
    status = 'published'
    AND (expires_at IS NULL OR expires_at >= NOW())
    AND EXISTS (
      SELECT 1
      FROM public.profiles AS treasurer
      WHERE treasurer.id = auth.uid()
        AND treasurer.role = 'zone_treasurer'
        AND (
          announcements.target_audience = 'all_zone_treasurers'
          OR (
            announcements.target_audience = 'specific_zone'
            AND announcements.zone_id = treasurer.zone_id
          )
        )
    )
  );
